CREATE TABLE puzzle (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(120) NOT NULL,
 description VARCHAR(500),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE word_group (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 puzzle_id BIGINT NOT NULL REFERENCES puzzle(id) ON DELETE CASCADE,
 category VARCHAR(120) NOT NULL,
 explanation TEXT NOT NULL,
 CONSTRAINT uq_group_category_per_puzzle UNIQUE (puzzle_id, category)
);
CREATE TABLE word (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 word_group_id BIGINT NOT NULL REFERENCES word_group(id) ON DELETE CASCADE,
 value VARCHAR(60) NOT NULL,
 CONSTRAINT uq_word_value UNIQUE (word_group_id, value)
);
CREATE TABLE game_session (
 id UUID PRIMARY KEY,
 puzzle_id BIGINT NOT NULL REFERENCES puzzle(id),
 player_name VARCHAR(80) NOT NULL,
 score INTEGER NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 100),
 mistakes INTEGER NOT NULL DEFAULT 0 CHECK (mistakes >= 0),
 completed BOOLEAN NOT NULL DEFAULT FALSE,
 started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 finished_at TIMESTAMP
);
CREATE TABLE game_found_group (
 game_session_id UUID NOT NULL REFERENCES game_session(id) ON DELETE CASCADE,
 word_group_id BIGINT NOT NULL REFERENCES word_group(id),
 found_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (game_session_id, word_group_id)
);
CREATE INDEX idx_word_group_puzzle ON word_group(puzzle_id);
CREATE INDEX idx_game_session_puzzle ON game_session(puzzle_id);
